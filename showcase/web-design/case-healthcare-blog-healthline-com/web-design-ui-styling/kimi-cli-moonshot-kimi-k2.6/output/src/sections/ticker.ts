export function renderTicker(): string {
  const stats = [
    { icon: 'shield', text: 'Medically reviewed content' },
    { icon: 'users', text: '145 medical reviewers in network' },
    { icon: 'calendar', text: '21 years of experience' },
    { icon: 'globe', text: '55 million monthly readers' },
  ]

  const statHtml = stats.map(s => `
    <div class="flex items-center gap-2 shrink-0 px-6">
      <div class="w-6 h-6 rounded-full bg-primary-light flex items-center justify-center">
        ${renderIcon(s.icon)}
      </div>
      <span class="text-sm font-medium text-charcoal whitespace-nowrap">${s.text}</span>
    </div>
  `).join('')

  return `
<section class="bg-primary-light border-b border-border-light overflow-hidden" aria-label="Credibility stats">
  <div class="relative py-2.5">
    <div class="animate-ticker flex items-center w-max">
      ${statHtml}
      ${statHtml}
      ${statHtml}
      ${statHtml}
    </div>
  </div>
</section>
`
}

